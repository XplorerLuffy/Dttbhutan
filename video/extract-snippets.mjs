function read(path) {
  return fs.readFileSync(path, "utf8").split("\n");
}

/** Finds a block by the line it starts on and how many lines to take. */
function grab(path, startsWith, count, { skipComments = false } = {}) {
  const lines = read(path);
  const i = lines.findIndex((l) => l.trimStart().startsWith(startsWith));
  if (i === -1) throw new Error(`"${startsWith}" not found in ${path}`);
  const slice = lines.slice(i, i + count);
  return { code: slice.join("\n"), startLine: i + 1 };
}

const out = {};

function add(key, path, startsWith, count) {
  const { code, startLine } = grab(path, startsWith, count);
  out[key] = { path, startLine, code };
  console.log(`${key.padEnd(18)} ${path}:${startLine}  (${count} lines)`);
}

