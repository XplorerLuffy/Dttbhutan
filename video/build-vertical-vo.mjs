/**
 * Works out when each line of the vertical cut's narration is spoken.
 *
 * Run from video/: node build-vertical-vo.mjs
 *
 * Same method as build-vo-timing.mjs — estimate each line's share of the
 * spoken characters, then snap the boundary to a pause ffmpeg can hear — but
 * for the shorter script and with the caption text carried through, because in
 * the vertical cut the words are on screen as well as in the ear. Most people
 * meet a TikTok muted.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const AUDIO = "public/audio/vertical-vo.mp3";

/** [id, spoken text, what the caption reads]. The caption is shorter than the
 * line: a phone cannot hold a whole sentence at a size worth reading. */
const LINES = [
  ["hook", "I built this travel website for a client in Bhutan.", "I built this travel website\nfor a client in Bhutan"],
  ["platform", "Twenty-nine tour packages. All twenty districts. Day-by-day itineraries, with real prices.", "29 tour packages\nAll 20 districts\nReal prices"],
  ["backend", "Behind it — forty API routes, thirty-four database models, five kinds of account.", "40 API routes\n34 database models\n5 kinds of account"],
  ["turn", "Then I wanted more than a website.", "Then I wanted more\nthan a website"],
  ["ai", "So I built an AI travel assistant, and put it inside the site.", "So I built an\nAI travel assistant"],
  ["knowledge", "It doesn't answer from general AI knowledge. I gave it its own — fifty-seven documents about Bhutan travel, searchable by meaning.", "Not general AI knowledge —\n57 documents about Bhutan,\nsearchable by meaning"],
  ["rag", "Ask it about Bhutan's daily fee, and it searches that first, then answers from what it actually found.", "It searches that first,\nthen answers from\nwhat it found"],
  ["everywhere", "Now it's on every page.", "Now it's on every page"],
  ["cta", "I'm Jambay, and I build websites like this. Jambayang dot com.", "I build websites like this\njambayang.com"],
];

const duration = Number(
  execFileSync("ffprobe", [
    "-v", "error", "-show_entries", "format=duration",
    "-of", "default=noprint_wrappers=1:nokey=1", AUDIO,
  ]).toString().trim()
);

const detect = execFileSync(
  "bash",
  ["-c", `ffmpeg -hide_banner -i "${AUDIO}" -af silencedetect=noise=-37dB:d=0.10 -f null - 2>&1`],
  { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 }
);
const starts = [...detect.matchAll(/silence_start: ([0-9.]+)/g)].map((m) => Number(m[1]));
const ends = [...detect.matchAll(/silence_end: ([0-9.]+)/g)].map((m) => Number(m[1]));
const gaps = starts.map((s, i) => ({ start: s, end: ends[i], length: ends[i] - s })).filter((g) => g.end);

const weights = LINES.map(([, text]) => text.replace(/\s+/g, " ").trim().length);
const total = weights.reduce((a, b) => a + b, 0);

let cursor = 0;
const rows = LINES.map(([id, text, caption], i) => {
  const estimate = cursor;
  cursor += (weights[i] / total) * duration;
  if (i === 0) return { id, text, caption, start: 0, note: "start of file" };

  // Score by length as well as closeness. A break between two lines is a
  // longer pause than the comma inside one, and closeness alone picked the
  // comma more than once — which put a line's last clause under the next
  // line's picture. 0.35s of distance is worth as much as 1s of pause.
  //
  // The detector runs down to a tenth of a second because one real break in
  // this take is only 0.11s long — the one between "Then I wanted more than a
  // website" and "So I built an AI travel assistant", which is the pivot of
  // the whole video and the last place a mis-timed caption is acceptable.
  const near = gaps
    .filter((g) => Math.abs(g.start - estimate) <= 1.8)
    .sort((a, b) => b.length - 0.35 * Math.abs(b.start - estimate) - (a.length - 0.35 * Math.abs(a.start - estimate)));
  const pick = near[0];
  return {
    id,
    text,
    caption,
    start: pick ? +((pick.start + pick.end) / 2).toFixed(2) : +estimate.toFixed(2),
    note: pick ? `gap ${pick.length.toFixed(2)}s @ ${pick.start.toFixed(2)}` : "NO GAP — estimate kept",
  };
});

console.log(`vertical voiceover: ${duration.toFixed(2)}s, ${gaps.length} pauses\n`);
rows.forEach((r, i) => {
  const end = i + 1 < rows.length ? rows[i + 1].start : duration;
  const words = r.text.split(/\s+/).length;
  console.log(
    `${r.id.padEnd(12)} ${r.start.toFixed(2).padStart(6)} -> ${end.toFixed(2).padStart(6)}  (${(end - r.start)
      .toFixed(2)
      .padStart(5)}s, ${(words / (end - r.start)).toFixed(2)} w/s)  ${r.note}`
  );
});

fs.writeFileSync(
  "src/data/verticalVoiceover.ts",
  `/**
 * The vertical cut's narration: when each line is spoken, and what the caption
 * on screen reads while it is.
 *
 * GENERATED by video/build-vertical-vo.mjs — do not edit by hand.
 *
 * \`caption\` is deliberately shorter than \`text\`. The line is what is said; the
 * caption is what fits on a phone at a size worth reading, for the viewers who
 * meet the video muted — which on TikTok is most of them.
 */
export type VerticalLine = { id: string; start: number; end: number; text: string; caption: string };

export const VERTICAL_VO_DURATION = ${duration.toFixed(3)};

export const VERTICAL_VO: VerticalLine[] = ${JSON.stringify(
    rows.map((r, i) => ({
      id: r.id,
      start: r.start,
      end: i + 1 < rows.length ? rows[i + 1].start : +duration.toFixed(2),
      text: r.text,
      caption: r.caption,
    })),
    null,
    2
  )};
`
);
console.log("\nwrote src/data/verticalVoiceover.ts");
