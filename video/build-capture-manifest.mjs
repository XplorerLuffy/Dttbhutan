/**
 * Records the real pixel size of every capture.
 *
 * Run from video/: node build-capture-manifest.mjs
 *
 * BrowserFrame needs a capture's aspect ratio to know how far a pan can
 * travel. Passing it by hand at each call site was wrong in a way that was easy
 * to miss and hard to see: a homepage capture nearly 7 times taller than it is
 * wide was declared as 2.9, so "pan from the top to the footer" stopped less
 * than half way down and simply looked like a slow scene.
 *
 * Reading it from the files removes the chance of that ever being wrong again,
 * and re-running after a re-shoot keeps the pans correct for the new captures.
 */
import fs from "node:fs";
import path from "node:path";

const DIR = "public/captures";

/** PNG: width and height are the two big-endian uint32s in the IHDR chunk. */
function pngSize(file) {
  const fd = fs.openSync(file, "r");
  const head = Buffer.alloc(24);
  fs.readSync(fd, head, 0, 24, 0);
  fs.closeSync(fd);
  if (head.toString("ascii", 1, 4) !== "PNG") throw new Error(`${file} is not a PNG`);
  return { width: head.readUInt32BE(16), height: head.readUInt32BE(20) };
}

const sizes = {};
for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith(".png")).sort()) {
  sizes[file.replace(/\.png$/, "")] = pngSize(path.join(DIR, file));
}

fs.writeFileSync(
  "src/data/captureSizes.ts",
  `/**
 * The real pixel size of every capture in public/captures.
 *
 * GENERATED by video/build-capture-manifest.mjs — do not edit by hand.
 * BrowserFrame reads it to work out how far a pan can travel; see that file.
 */
export const CAPTURE_SIZES: Record<string, { width: number; height: number }> = ${JSON.stringify(
    sizes,
    null,
    2
  )};
`
);

console.log(`${Object.keys(sizes).length} captures measured -> src/data/captureSizes.ts`);
for (const [name, s] of Object.entries(sizes)) {
  if (s.height / s.width > 2) console.log(`  tall: ${name.padEnd(30)} ${s.width}x${s.height}`);
}
