/**
 * Where each line of the client-story narration falls, and what the on-screen
 * text beside it reads.
 *
 * Run from video/: node build-client-vo.mjs
 *
 * Same method as the other two: estimate each line's share of the spoken
 * characters, then snap the boundary to a pause ffmpeg can hear, scoring by
 * pause length as well as closeness so a sentence break wins over a comma.
 *
 * `onScreen` is the client's own script — the words they asked to appear at
 * that moment, not a caption I wrote.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const AUDIO = "public/audio/client-vo.mp3";

/** [id, spoken line, on-screen text or null]. Twelve lines across ten beats:
 * "under the hood" and "personal brand" each carry two. */
const LINES = [
  ["hook", "Here's what I built for a travel client in Bhutan.", "Building a travel website for a real client 🇧🇹"],
  ["start", "I started with the idea of creating a modern platform where travelers could discover Bhutan and plan their journey.", "DTT BHUTAN — CLIENT PROJECT"],
  ["building", "First, I built the core website — the interface, travel pages, user flows, and the functionality behind them.", "DESIGN → DEVELOPMENT → FUNCTIONALITY"],
  ["hood1", "But a website isn't just what you see on the screen.", null],
  ["hood2", "I also built the backend, database architecture, authentication, and APIs powering the experience.", null],
  ["aiIdea", "Once the website was working, I wanted visitors to have someone they could actually ask about Bhutan.", "Then I wanted to take it further…"],
  ["assistant", "So I built an AI Travel Assistant and integrated it directly into the website.", "AI TRAVEL ASSISTANT"],
  ["howItWorks", "It can connect the conversation with travel knowledge, so the assistant can provide more relevant information about Bhutan.", null],
  ["result", "And this is the final result.", "DTT BHUTAN"],
  ["brand1", "This is one of the projects I'm building as a freelance web developer.", "JAMBAYANG.COM"],
  ["brand2", "I'm Jambayang, and I build websites and digital experiences for businesses.", null],
  ["end", "More builds coming soon.", "Building. Designing. Shipping."],
];

const duration = Number(
  execFileSync("ffprobe", [
    "-v", "error", "-show_entries", "format=duration",
    "-of", "default=noprint_wrappers=1:nokey=1", AUDIO,
  ]).toString().trim()
);

const detect = execFileSync(
  "bash",
  ["-c", `ffmpeg -hide_banner -i "${AUDIO}" -af silencedetect=noise=-37dB:d=0.10 -f null - 2>&1`],
  { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 }
);
const starts = [...detect.matchAll(/silence_start: ([0-9.]+)/g)].map((m) => Number(m[1]));
const ends = [...detect.matchAll(/silence_end: ([0-9.]+)/g)].map((m) => Number(m[1]));
const gaps = starts.map((s, i) => ({ start: s, end: ends[i], length: ends[i] - s })).filter((g) => g.end);

const weights = LINES.map(([, text]) => text.replace(/\s+/g, " ").trim().length);
const total = weights.reduce((a, b) => a + b, 0);

let cursor = 0;
const rows = LINES.map(([id, text, onScreen], i) => {
  const estimate = cursor;
  cursor += (weights[i] / total) * duration;
  if (i === 0) return { id, text, onScreen, start: 0, note: "start of file" };

  const near = gaps
    .filter((g) => Math.abs(g.start - estimate) <= 1.8)
    .sort(
      (a, b) =>
        b.length - 0.35 * Math.abs(b.start - estimate) - (a.length - 0.35 * Math.abs(a.start - estimate))
    );
  const pick = near[0];
  return {
    id,
    text,
    onScreen,
    start: pick ? +((pick.start + pick.end) / 2).toFixed(2) : +estimate.toFixed(2),
    note: pick ? `gap ${pick.length.toFixed(2)}s @ ${pick.start.toFixed(2)}` : "NO GAP — estimate kept",
  };
});

console.log(`client narration: ${duration.toFixed(2)}s of speech, ${gaps.length} pauses\n`);
console.log("line          start     end    len   w/s   snapped to");
let bad = 0;
rows.forEach((r, i) => {
  const end = i + 1 < rows.length ? rows[i + 1].start : duration;
  const len = end - r.start;
  const rate = r.text.split(/\s+/).length / len;
  const ok = rate > 1.7 && rate < 4.0;
  if (!ok) bad++;
  console.log(
    `${r.id.padEnd(12)} ${r.start.toFixed(2).padStart(6)} ${end.toFixed(2).padStart(7)} ${len
      .toFixed(2)
      .padStart(6)} ${rate.toFixed(2).padStart(5)}   ${r.note}${ok ? "" : "   <-- CHECK"}`
  );
});
console.log(bad === 0 ? "\nAll boundaries consistent with their text." : `\n${bad} boundary/ies look wrong.`);

fs.writeFileSync(
  "src/data/clientVoiceover.ts",
  `/**
 * The client-story narration: when each line is spoken, and the on-screen text
 * the script asks for alongside it.
 *
 * GENERATED by video/build-client-vo.mjs — do not edit by hand.
 *
 * \`onScreen\` is the client's own wording, not a caption written for them.
 */
export type ClientLine = { id: string; start: number; end: number; text: string; onScreen: string | null };

export const CLIENT_VO_DURATION = ${duration.toFixed(3)};

export const CLIENT_VO: ClientLine[] = ${JSON.stringify(
    rows.map((r, i) => ({
      id: r.id,
      start: r.start,
      end: i + 1 < rows.length ? rows[i + 1].start : +duration.toFixed(2),
      text: r.text,
      onScreen: r.onScreen,
    })),
    null,
    2
  )};
`
);
console.log("\nwrote src/data/clientVoiceover.ts");
